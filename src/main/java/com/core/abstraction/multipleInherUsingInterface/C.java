package com.core.abstraction.multipleInherUsingInterface;

public class C implements I 
{
	//multiple classes can implement same interface
		
	    public void m1()
		{
			System.out.println("m1 of I and I1--C ");
		}
		public void m2()
		{
			System.out.println("m2-I--C");
		}
		public void m3()
		{
			System.out.println("m3-I--C");
		}
		public void m8()
		{
			System.out.println("m8-I--C");
		}  

}
